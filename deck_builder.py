from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN

prs = Presentation()
prs.slide_width  = Inches(13.333)
prs.slide_height = Inches(7.5)

TITLE_CONTENT = prs.slide_layouts[1]
TITLE_ONLY    = prs.slide_layouts[5]

ACCENT = RGBColor(0x1F, 0x4E, 0x79)
DARK   = RGBColor(0x22, 0x22, 0x22)
GREY   = RGBColor(0x60, 0x60, 0x60)

def _style_title(slide, size=30):
    t = slide.shapes.title
    t.top, t.left, t.width, t.height = Inches(0.45), Inches(0.55), Inches(12.2), Inches(0.95)
    for p in t.text_frame.paragraphs:
        for r in p.runs:
            r.font.size, r.font.bold, r.font.color.rgb = Pt(size), True, ACCENT

def _footer(slide, n):
    box = slide.shapes.add_textbox(Inches(12.2), Inches(6.95), Inches(1.0), Inches(0.4))
    p = box.text_frame.paragraphs[0]
    p.text = str(n)
    p.font.size, p.font.color.rgb = Pt(11), GREY

def cover(title, lines):
    s = prs.slides.add_slide(TITLE_ONLY)
    s.shapes.title.text = title
    s.shapes.title.top, s.shapes.title.left = Inches(1.0), Inches(0.8)
    s.shapes.title.width, s.shapes.title.height = Inches(11.3), Inches(1.9)
    for p in s.shapes.title.text_frame.paragraphs:
        for r in p.runs:
            r.font.size, r.font.bold, r.font.color.rgb = Pt(34), True, ACCENT
    box = s.shapes.add_textbox(Inches(1.0), Inches(2.9), Inches(11.3), Inches(3.6))
    tf = box.text_frame
    tf.word_wrap = True
    for i, (lvl, txt) in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = txt
        p.level = lvl
        p.alignment = PP_ALIGN.CENTER
        for r in p.runs:
            r.font.size = Pt(16 if lvl == 0 else 14)
            r.font.color.rgb = DARK if lvl == 0 else GREY
    return s

def content(title, bullets, note=None):
    s = prs.slides.add_slide(TITLE_CONTENT)
    s.shapes.title.text = title
    _style_title(s)
    body = s.placeholders[1]
    body.top, body.left, body.width, body.height = Inches(1.55), Inches(0.65), Inches(12.0), Inches(5.2)
    tf = body.text_frame
    tf.word_wrap = True
    for i, (lvl, txt) in enumerate(bullets):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = txt
        p.level = lvl
        p.space_after = Pt(8)
        for r in p.runs:
            r.font.size = Pt(18 if lvl == 0 else 15)
            r.font.color.rgb = DARK if lvl == 0 else GREY
            r.font.bold = (lvl == 0 and txt.endswith(":"))
    if note:
        nb = s.shapes.add_textbox(Inches(0.65), Inches(6.75), Inches(11.5), Inches(0.55))
        p = nb.text_frame.paragraphs[0]
        p.text = note
        p.font.size, p.font.italic, p.font.color.rgb = Pt(12), True, GREY
    _footer(s, len(prs.slides._sldIdLst))
    return s

def table(title, headers, rows, widths=None, fsize=13, note=None):
    s = prs.slides.add_slide(TITLE_ONLY)
    s.shapes.title.text = title
    _style_title(s, 26)
    nr, nc = len(rows) + 1, len(headers)
    shp = s.shapes.add_table(nr, nc, Inches(0.6), Inches(1.6), Inches(12.1), Inches(4.7))
    tbl = shp.table
    if widths:
        for i, w in enumerate(widths):
            tbl.columns[i].width = Inches(w)
    # แถวยืดพอดีเนื้อหา ไม่ยืดเต็มความสูงคงที่ 4.7" (กันเซลล์โปร่งในตารางสั้น)
    tbl.rows[0].height = Inches(0.5)
    for i in range(1, len(tbl.rows)):
        tbl.rows[i].height = Inches(0.42)
    shp.height = Inches(0.5 + 0.42 * len(rows))
    for j, h in enumerate(headers):
        c = tbl.cell(0, j)
        c.text = h
        for p in c.text_frame.paragraphs:
            for r in p.runs:
                r.font.size, r.font.bold, r.font.color.rgb = Pt(fsize), True, RGBColor(0xFF,0xFF,0xFF)
    for i, row in enumerate(rows, start=1):
        for j, val in enumerate(row):
            c = tbl.cell(i, j)
            c.text = str(val)
            for p in c.text_frame.paragraphs:
                for r in p.runs:
                    r.font.size, r.font.color.rgb = Pt(fsize), DARK
    if note:
        nb = s.shapes.add_textbox(Inches(0.6), Inches(6.5), Inches(11.8), Inches(0.5))
        p = nb.text_frame.paragraphs[0]
        p.text = note
        p.font.size, p.font.italic, p.font.color.rgb = Pt(11), True, GREY
    _footer(s, len(prs.slides._sldIdLst))
    return s

